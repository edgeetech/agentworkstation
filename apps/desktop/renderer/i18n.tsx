const catalogs: Record<UiLocale, Record<MessageKey, string>> = { en, tr };
export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string;
const STORAGE_KEY = 'agent-workstation.ui-language';

function format(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

type I18nContextValue = { locale: UiLocale; setLocale: (locale: UiLocale) => void; t: Translator };
const I18nContext = createContext<I18nContextValue | null>(null);

function initialLocale(): UiLocale {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'tr' ? 'tr' : 'en';
  } catch {
    return 'en';
  }
}

export function I18nProvider({ children }: { children: ReactNode }): JSX.Element {
  const [locale, setLocaleState] = useState<UiLocale>(initialLocale);
  const setLocale = (nextLocale: UiLocale): void => {
    setLocaleState(nextLocale);
    try { localStorage.setItem(STORAGE_KEY, nextLocale); } catch { /* The UI can still switch for this run. */ }
  };
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);
  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t: (key, values) => format(catalogs[locale][key], values),
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
